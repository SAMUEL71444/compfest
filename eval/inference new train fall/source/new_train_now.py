def geom_features(win):
    """
    win: [T,17,3] (x,y,conf) SUDAH ternormalisasi (origin=pinggul, skala torso).
    Return: (sudut_torso_maks_derajat, kecepatan_gerak_maks)

    - sudut torso: sudut vektor pinggul->bahu thd VERTIKAL. 0=tegak, 90=rebah.
    - kecepatan  : DIPERBAIKI. Karena origin=pinggul, pinggul nyaris diam ->
                   kecepatan dari diff pinggul = 0 (bug v1). Sebagai gantinya
                   diukur dari laju perubahan VEKTOR TORSO (pinggul->bahu)
                   antar-frame. Saat jatuh, torso berubah orientasi cepat ->
                   kecepatan besar. Saat duduk pelan -> kecil.
    """
    xy  = win[:, :, :2]
    hip = (xy[:, COCO['L_hip']] + xy[:, COCO['R_hip']]) / 2.0
    sho = (xy[:, COCO['L_sho']] + xy[:, COCO['R_sho']]) / 2.0
    dvec = sho - hip                                            # vektor torso [T,2]
    ang = np.degrees(np.arctan2(np.abs(dvec[:, 0]), np.abs(dvec[:, 1]) + 1e-6))
    ang_max = float(np.max(ang))
    if dvec.shape[0] >= 2:
        step = np.linalg.norm(np.diff(dvec, axis=0), axis=1)   # perpindahan/frame
        vel_max = float(np.max(step) * FPS)                    # per detik
    else:
        vel_max = 0.0
    return ang_max, vel_max

