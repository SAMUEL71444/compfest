    pred = ((p_fall >= tp) & (torso_angle >= ta) & (fall_speed >= ts)).astype(int)
    tp_ = int(((pred==1)&(y_fall==1)).sum()); fp_ = int(((pred==1)&(y_fall==0)).sum())
    fn_ = int(((pred==0)&(y_fall==1)).sum()); tn_ = int(((pred==0)&(y_fall==0)).sum())
