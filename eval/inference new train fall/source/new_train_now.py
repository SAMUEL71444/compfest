def eval_thresh(tp, ta, ts):
    pred = ((p_fall >= tp) & (torso_angle >= ta) & (fall_speed >= ts)).astype(int)
    tp_ = int(((pred==1)&(y_fall==1)).sum()); fp_ = int(((pred==1)&(y_fall==0)).sum())
    fn_ = int(((pred==0)&(y_fall==1)).sum()); tn_ = int(((pred==0)&(y_fall==0)).sum())
    recall    = tp_/max(tp_+fn_,1)
    precision = tp_/max(tp_+fp_,1)
    f1        = 2*precision*recall/max(precision+recall,1e-9)
    far       = fp_/max(fp_+tn_,1)
    return dict(T_prob=tp, T_angle=int(ta), T_speed=float(ts),
                recall_jatuh=round(recall,4), precision_jatuh=round(precision,4),
                f1_jatuh=round(f1,4), false_alarm=round(far,4),
                TP=tp_, FP=fp_, FN=fn_, TN=tn_)

rows = [eval_thresh(tp, ta, ts) for tp in T_PROBS for ta in T_ANGLES for ts in T_SPEEDS]
